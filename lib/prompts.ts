export function documentUserPrompt(project: Project) {
  const qa = (project.questions ?? [])
    .map((q) => `Вопрос: ${q.text}\nОтвет: ${(project.answers ?? {})[q.id] ?? "—"}`)
    .join("\n\n");
  return `Бизнес-идея: """${project.idea}"""\n\nОтветы пользователя на уточняющие вопросы:\n${qa}\n\nСоздай документ по схеме.`;
}

