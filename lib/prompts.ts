export function documentUserPrompt(project: Project) {
const qa = (project.questions ?? [])
.map(
(q) =>
`Вопрос: ${q.text}\nОтвет: ${(project.answers ?? {})[q.id] ?? "—"}`
)
.join("\n\n");

return `Бизнес-идея: """${project.idea}"""

Ответы пользователя на уточняющие вопросы:
${qa}

Создай документ по схеме.`;
}

